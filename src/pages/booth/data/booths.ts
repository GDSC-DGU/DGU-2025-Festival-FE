const S3_BASE_URL = "https://dgu-festival.s3.ap-northeast-2.amazonaws.com/images/booth";


function getBoothImages(
  boothId: string | number,
  count: number,
  ext: string | string[] = "jpg"
): string[] {
  return Array.from({ length: count }, (_, i) => {
    const extension = Array.isArray(ext) ? ext[i] || ext[0] : ext;
    return `${S3_BASE_URL}/${boothId}-${i + 1}.${extension}`;
  });
}

